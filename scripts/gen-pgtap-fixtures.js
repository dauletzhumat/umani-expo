#!/usr/bin/env node
/**
 * Generates supabase/tests/900_fixture_parity.test.sql from the shared fixtures in
 * supabase/fixtures/*.json, so the SQL implementation is checked against exactly the
 * same vectors as the TypeScript domain (CLAUDE.md, "Testing").
 *
 * Run via `npm run db:fixtures` (from the project root). CI fails if the generated
 * file is out of date.
 */
const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const BASE_CURRENCY = 'KZT'; // fixtures are written for a KZT base (see fx.json description)
const OUTPUT = path.join(ROOT, 'supabase', 'tests', '900_fixture_parity.test.sql');

const read = (name) => JSON.parse(fs.readFileSync(path.join(ROOT, 'supabase', 'fixtures', name), 'utf8'));
const allocation = read('allocation.json');
const fx = read('fx.json');
const rounding = read('rounding.json');

const INTEGER = /^-?(0|[1-9][0-9]*)$/;
const RATE = /^[0-9]+(\.[0-9]{1,12})?$/;
const CURRENCY = /^[A-Z]{3}$/;

function int(value) {
  if (!INTEGER.test(value)) throw new Error(`Not an integer string: ${value}`);
  return `${value}::bigint`;
}
function rate(value) {
  if (value === null) return 'null::numeric';
  if (!RATE.test(value)) throw new Error(`Not a rate: ${value}`);
  return `${value}::numeric`;
}
function currency(value) {
  if (!CURRENCY.test(value)) throw new Error(`Not a currency: ${value}`);
  return `'${value}'`;
}
function label(text) {
  return `'${text.replace(/'/g, "''")}'`;
}

const tests = [];

for (const c of rounding.divideHalfEven) {
  // numerators may exceed bigint, so compare as numeric
  if (![c.numerator, c.denominator, c.expected].every((v) => INTEGER.test(v))) {
    throw new Error(`Bad rounding case ${JSON.stringify(c)}`);
  }
  tests.push(
    `select is(private.div_half_even(${c.numerator}::numeric, ${c.denominator}::numeric), ${c.expected}::numeric, ` +
      `${label(`div_half_even: ${c.numerator} / ${c.denominator}`)});`,
  );
}

for (const c of allocation.cases) {
  const weights = c.weightsBps.map((w) => {
    if (!Number.isInteger(w)) throw new Error(`Bad weight in ${c.name}`);
    return String(w);
  });
  tests.push(
    `select is(private.allocate_bps(${int(c.total)}, array[${weights.join(', ')}]::int[]), ` +
      `array[${c.expected.map(int).join(', ')}]::bigint[], ${label(`allocation: ${c.name}`)});`,
  );
}

for (const c of fx.incoming) {
  tests.push(
    `select is(private.book_in(${int(c.amount)}, ${currency(c.currency)}, '${BASE_CURRENCY}', ${rate(c.rate)}), ` +
      `${int(c.expectedBase)}, ${label(`fx incoming: ${c.name}`)});`,
  );
}

for (const c of fx.outgoing) {
  tests.push(
    `select is(private.book_out(${int(c.balance)}, ${int(c.bookValue)}, ${int(c.amount)}, ${currency(c.currency)}, ` +
      `'${BASE_CURRENCY}', ${rate(c.rate)}), ${int(c.expectedBase)}, ${label(`fx outgoing: ${c.name}`)});`,
  );
}

for (const c of fx.transfer) {
  const baseOut =
    `private.book_out(${int(c.balance)}, ${int(c.bookValue)}, ${int(c.sent)}, ${currency(c.fromCurrency)}, ` +
    `'${BASE_CURRENCY}', ${rate(c.rate)})`;
  // Same rule as private.post_transfer: a base-currency destination holds what it received.
  const baseIn = c.toCurrency === BASE_CURRENCY ? int(c.received) : baseOut;
  tests.push(`select is(${baseOut}, ${int(c.expectedBaseOut)}, ${label(`fx transfer out: ${c.name}`)});`);
  if (c.toCurrency !== BASE_CURRENCY) {
    // only meaningful when base-in is computed (carried book value); otherwise it is the fixture itself
    tests.push(`select is(${baseIn}, ${int(c.expectedBaseIn)}, ${label(`fx transfer in: ${c.name}`)});`);
  }
  tests.push(
    `select is(${baseIn} - ${baseOut}, ${int(c.expectedFxResult)}, ${label(`fx transfer result: ${c.name}`)});`,
  );
}

for (const c of fx.revalue) {
  const target = `private.convert(${int(c.balance)}, ${currency(c.currency)}, ${rate(c.rate)}, '${BASE_CURRENCY}')`;
  tests.push(`select is(${target}, ${int(c.expectedTarget)}, ${label(`fx revalue target: ${c.name}`)});`);
  tests.push(
    `select is(${target} - ${int(c.bookValue)}, ${int(c.expectedDelta)}, ${label(`fx revalue delta: ${c.name}`)});`,
  );
}

const sql = [
  '-- GENERATED by scripts/gen-pgtap-fixtures.js from supabase/fixtures/*.json. Do not edit.',
  '-- Parity: the SQL money/FX functions must match the TypeScript domain on the shared vectors.',
  'begin;',
  'create extension if not exists pgtap with schema extensions;',
  `select plan(${tests.length});`,
  '',
  ...tests,
  '',
  'select * from finish();',
  'rollback;',
  '',
].join('\n');

fs.writeFileSync(OUTPUT, sql);
console.log(`gen-pgtap-fixtures: wrote ${tests.length} tests to ${path.relative(ROOT, OUTPUT)}`);
